import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { BACKGROUND_CONTEXT } from "@p2/app/v1";
import { Projects } from "../../plugins/projects/contract.ts";
import { Sessions } from "../../plugins/sessions/contract.ts";
import { Browser, browserTests } from "./browser.ts";
import { holdIn, startFixture } from "./helpers.ts";

test("uses a project’s default location and opens a project session from the sidebar", { skip: !browserTests }, async (t) => {
	const fixture = await startFixture({ web: true });
	t.after(() => fixture.close());
	const browser = await Browser.start();
	t.after(() => browser.close());
	const host = fixture.browser();
	const projects = await holdIn(host, Projects, {}, "owner");
	const sessions = await holdIn(host, Sessions, {}, "owner");
	const path = join(fixture.workspace, "sidebar-project");
	mkdirSync(path);
	await projects.create({ name: "Sidebar project", place: { env: null, path } }, BACKGROUND_CONTEXT);
	await browser.metrics(1280, 900);
	await browser.signIn(fixture.owner);
	await browser.open(`http://127.0.0.1:${fixture.server.port}/new`);
	await browser.wait(`document.querySelector(".project-pick span")?.textContent === "No project"`);
	await browser.click(".project-pick");
	const choice = `[...document.querySelectorAll(".command-menu [role=option]")].find(row => row.querySelector(".command-title")?.textContent === "Sidebar project")`;
	await browser.wait(choice);
	await browser.evaluate(`(${choice}).click()`);
	await browser.wait(`document.querySelector(".cwd-pick span")?.textContent.endsWith("/sidebar-project")`);
	const created = await sessions.create({ title: "Sidebar fixture session", cwd: path }, BACKGROUND_CONTEXT);
	await projects.assign({ session: created.id, project: "Sidebar project" }, BACKGROUND_CONTEXT);
	const row = `[data-project="Sidebar project"] a.session-main[href="/s/${created.id}"]`;
	await browser.wait(`document.querySelector(${JSON.stringify(row)})?.textContent.includes("Sidebar fixture session")`);
	await browser.click(row);
	await browser.wait(`location.pathname === "/s/${created.id}" && document.querySelector(".session-header .session-title")?.textContent.includes("Sidebar fixture session")`);
});
